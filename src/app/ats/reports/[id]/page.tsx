import { headers } from "next/headers";
import { notFound, redirect } from "next/navigation";

import { getRuntimePool } from "@/infrastructure/database/runtime";
import { AtsReportContent } from "@/modules/ats/components/report-content";
import { AtsInputNotFoundError, AtsRepository } from "@/modules/ats/repository";
import { getCurrentPrincipal } from "@/modules/auth/principal";

export const dynamic = "force-dynamic";

export default async function AtsReportPage({
  params,
}: {
  params: Promise<{ id: string }>;
}) {
  const principal = await getCurrentPrincipal(await headers());
  if (!principal) redirect("/");
  const { id } = await params;
  let view;
  try {
    view = await new AtsRepository(getRuntimePool()).getReport(principal, id);
  } catch (error) {
    if (error instanceof AtsInputNotFoundError) notFound();
    throw error;
  }
  const report = view.report;
  return (
    <AtsReportContent
      analyzeHref={`/ats?documentId=${report.document_id}`}
      analyzeLabel="Analyze current version"
      backHref={`/documents/${report.document_id}`}
      backLabel={report.document_title}
      categories={view.categories}
      findingSurface
      findings={view.findings}
      notice="This report is generated by AI and can vary by provider or model. It is an estimate, not a proprietary ATS result, ranking, or hiring prediction. It never controls factual grounding or export eligibility."
      report={report}
      resumeIdentity={{
        label: "Document version and hash",
        value: `${report.document_version_id} \u00b7 ${report.document_hash}`,
      }}
      showCreatedAt
      subject={report.document_title}
    />
  );
}
